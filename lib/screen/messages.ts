export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, de };

export function formatMessage(key: MessageKey, params: Record<string, string | number> = {}, locale: Locale = 'en'): string {
  return MESSAGES[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => (params[name] === undefined ? `{${name}}` : String(params[name])));
}
